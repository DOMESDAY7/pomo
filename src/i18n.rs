static LANG: OnceLock<Lang> = OnceLock::new();

pub fn lang() -> Lang {
    *LANG.get_or_init(|| {
        let page = document()
            .document_element()
            .and_then(|e| e.get_attribute("lang"))
            .unwrap_or_default();
        Lang::ALL
            .into_iter()
            .find(|l| page.starts_with(l.code()))
            .unwrap_or(Lang::Fr)
    })
}

pub fn tr() -> &'static Strings {
    lang().strings()
}

/// "1,5 h" / "1.5h" / "1,5 Std."
pub fn hours(h: f64) -> String {
    let n = format!("{h:.1}");
    let n = if lang() == Lang::En { n } else { n.replace('.', ",") };
    format!("{n}{}", tr().hours_unit)
}

/// Messages from older versions saved the French defaults verbatim. Treat
/// them as "default" so other pages show their own language.
pub fn is_legacy_default(msg: &str) -> bool {
    msg == FR.default_msg_pomodoro || msg == FR.default_msg_break
}
