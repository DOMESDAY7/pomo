//! UI strings. The language comes from `<html lang>`: `/` is French and
//! `/en/`, `/es/`, `/de/`, `/pt/` are generated at build time, each page being
//! its own crawlable URL. Every language must fill every field, so a missing
//! translation fails to compile.

use leptos::prelude::document;
use std::sync::OnceLock;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Fr,
    En,
    Es,
    De,
    Pt,
}

impl Lang {
    pub const ALL: [Lang; 5] = [Lang::Fr, Lang::En, Lang::Es, Lang::De, Lang::Pt];

    pub fn code(self) -> &'static str {
        match self {
            Lang::Fr => "fr",
            Lang::En => "en",
            Lang::Es => "es",
            Lang::De => "de",
            Lang::Pt => "pt",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Fr => "Français",
            Lang::En => "English",
            Lang::Es => "Español",
            Lang::De => "Deutsch",
            Lang::Pt => "Português",
        }
    }

    /// Page path relative to the site root (pages under a subfolder set
    /// `<base href="../">`, so this works from every page).
    pub fn href(self) -> &'static str {
        match self {
            Lang::Fr => "./",
            Lang::En => "en/",
            Lang::Es => "es/",
            Lang::De => "de/",
            Lang::Pt => "pt/",
        }
    }

    fn strings(self) -> &'static Strings {
        match self {
            Lang::Fr => &FR,
            Lang::En => &EN,
            Lang::Es => &ES,
            Lang::De => &DE,
            Lang::Pt => &PT,
        }
    }
}

